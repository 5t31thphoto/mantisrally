#!/usr/bin/env python3
"""Mantis Motors art -> src/store_art.h
  * the side profiles from vehicles_sheet.jpg (the gold standard), full colour for the store screen (RGB565,
    0 = clear), at most 140 x 88
  * the MANTIS MOTORS arrow sign from signs_sheet.jpg as a world template (material << 4 | shade):
    yellow = the lit road-paint yellow, lettering = ink, post = rock grey
Run: python3 make_store_art.py"""
import numpy as np, os
from PIL import Image
import make_vehicles as M
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'src', 'store_art.h')
TM_ROCK, TM_SIGNY, TM_INK = 4, 13, 14

def side(name, box, tw_max=140, th_max=88):
    S, Ms = M.load_view(Image.open(os.path.join(HERE, 'vehicles_sheet.jpg')).convert('RGB'), box, False)
    rows = Ms.mean(1)
    for k in range(3):                                   # the last of the sheet's ground line under the wheels
        if rows[-1] > 0.25: S, Ms = S[:-1], Ms[:-1]; rows = rows[:-1]
    h, w = Ms.shape
    tw = tw_max; th = int(round(h * tw / w))
    if th > th_max: th = th_max; tw = int(round(w * th / h))
    rgba = np.zeros((h, w, 4), np.uint8); rgba[..., :3] = S.astype(np.uint8); rgba[..., 3] = Ms * 255
    a = np.asarray(Image.fromarray(rgba).resize((tw, th), Image.LANCZOS)).astype(int)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
    v = np.where(v == 0, 0x0821, v)                      # true black stays visible
    v = np.where(a[..., 3] > 140, v, 0)
    return tw, th, v.astype(np.uint16)

def sign():
    im = Image.open(os.path.join(HERE, 'signs_sheet.jpg')).convert('RGB').crop((20, 690, 492, 972))
    a = np.asarray(im.resize((64, 38), Image.LANCZOS)).astype(int)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    mx = a.max(2); mn = a.min(2); sat = mx - mn; lum = (r * 0.3 + g * 0.59 + b * 0.11)
    t = np.zeros((38, 64), np.uint8)
    yellow = (r > 140) & (g > 100) & (b < 120) & (sat > 70)
    ink = (lum < 95) & ~yellow
    post = (sat < 35) & (lum >= 95) & (lum < 160)
    post[:22, :] = False                                 # the post is only below the board
    t[yellow] = (TM_SIGNY << 4) | np.clip((lum[yellow] - 110) / 9, 0, 15).astype(np.uint8)
    t[ink] = (TM_INK << 4) | 2
    t[post] = (TM_ROCK << 4) | np.clip((lum[post] - 60) / 8, 0, 15).astype(np.uint8)
    cols = np.where(post.any(0))[0]
    ax = int(cols.mean()) if len(cols) else 32
    prev = np.zeros((38, 64, 3), np.uint8) + 200
    prev[yellow] = (240, 200, 40); prev[ink] = (30, 30, 70); prev[post] = (130, 130, 130)
    Image.fromarray(prev).resize((256, 152), Image.NEAREST).save(os.path.join(HERE, 'sign_preview.png'))
    return t, ax

def main():
    with open(OUT, 'w') as f:
        f.write('// Generated by tools/sprites/make_store_art.py (vehicles_sheet.jpg, signs_sheet.jpg). Do not edit.\n')
        f.write('#pragma once\n#include <stdint.h>\nnamespace mantis {\nnamespace art {\n')
        names = []
        for name, sb, rb, L, Wd, Hh, fill in M.VEH:
            w, h, v = side(name, sb)
            names.append((name, w, h))
            f.write('static const uint16_t SIDE_%s[%d] = {\n' % (name, w * h))
            flat = v.ravel()
            for i in range(0, len(flat), 24): f.write('  ' + ','.join(str(int(x)) for x in flat[i:i + 24]) + ',\n')
            f.write('};\n')
        f.write('struct SideArt { uint8_t w, h; const uint16_t* px; };\n')
        f.write('static const SideArt SIDE_ART[4] = {\n')
        for name, w, h in names: f.write('  {%d, %d, SIDE_%s},\n' % (w, h, name))
        f.write('};\n')
        # the rear drawings at photo resolution (the photo mode's rear angle)
        rnames = []
        for name, sb, rb, L, Wd, Hh, fill in M.VEH:
            w, h, v = side(name, rb, 110 if name != 'BIKE' else 60, 100)
            rnames.append((name, w, h))
            f.write('static const uint16_t REAR_%s[%d] = {\n' % (name, w * h))
            flat = v.ravel()
            for i in range(0, len(flat), 24): f.write('  ' + ','.join(str(int(x)) for x in flat[i:i + 24]) + ',\n')
            f.write('};\n')
        f.write('static const SideArt REAR_ART[4] = {\n')
        for name, w, h in rnames: f.write('  {%d, %d, REAR_%s},\n' % (w, h, name))
        f.write('};\n')
        t, ax = sign()
        # the left-pointing sign: the board flipped, the lettering copied back unflipped so it still reads
        tl = t[:, ::-1].copy()
        ink = (t >> 4) == TM_INK
        yel = (t >> 4) == TM_SIGNY
        def near(mask, dy, dx, n):                       # yellow within n pixels in a direction
            out = np.zeros_like(mask)
            for k in range(1, n + 1): out |= np.roll(np.roll(mask, dy * k, 0), dx * k, 1)
            return out
        letters = ink & near(yel, 0, 1, 7) & near(yel, 0, -1, 7) & near(yel, 1, 0, 5) & near(yel, -1, 0, 5)
        ys, xs = np.where(letters)
        x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
        tl[y0:y1 + 1, 63 - x1:63 - x0 + 1] = t[y0:y1 + 1, x0:x1 + 1]
        f.write('// MANTIS MOTORS arrow signs: pointing right, and pointing left (lettering still reads)\n')
        f.write('static const uint8_t MM_SIGN_W = 64, MM_SIGN_H = 38, MM_SIGN_AX = %d, MM_SIGN_AXL = %d;\n' % (ax, 63 - ax))
        for nm, arr in (('MM_SIGN', t), ('MM_SIGN_L', tl)):
            f.write('static const uint8_t %s[64 * 38] = {\n' % nm)
            flat = arr.ravel()
            for i in range(0, len(flat), 32): f.write('  ' + ','.join(str(int(x)) for x in flat[i:i + 32]) + ',\n')
            f.write('};\n')
        prev = np.zeros((38, 64, 3), np.uint8) + 200
        m = tl >> 4
        prev[m == TM_SIGNY] = (240, 200, 40); prev[m == TM_INK] = (30, 30, 70); prev[m == TM_ROCK] = (130, 130, 130)
        Image.fromarray(prev).resize((256, 152), Image.NEAREST).save(os.path.join(HERE, 'sign_preview_left.png'))
        f.write('}\n}\n')
    print('wrote', OUT, names)

if __name__ == '__main__':
    main()
