#!/usr/bin/env python3
"""Packs the art (raw/vehicle_art.h, raw/cockpit_art.h, raw/store_art.h) into one deflate-compressed blob:
src/art_packed.h. The game unpacks it into PSRAM once at boot (src/art.cpp) - every byte comes back exactly.
Run after any of make_vehicles.py / make_cockpits.py / make_store_art.py:   python3 pack_art.py"""
import re, os, zlib, struct
HERE = os.path.dirname(os.path.abspath(__file__))
RAW = os.path.join(HERE, 'raw')
OUT = os.path.join(HERE, '..', '..', 'src', 'art_packed.h')

def parse(fn):
    s = open(os.path.join(RAW, fn)).read()
    arrays, consts, tables = {}, {}, {}
    for m in re.finditer(r'static const (uint8_t|uint16_t) (\w+)\[([^\]]+)\]\s*=\s*\{', s):
        t, name, dim = m.groups()
        body = s[m.end():s.index('};', m.end())]
        vals = [int(v) for v in body.replace('\n', '').split(',') if v.strip()]
        arrays[name] = (t, vals)
    for m in re.finditer(r'static const uint8_t ((?:MM_SIGN_\w+\s*=\s*\d+\s*,?\s*)+);', s):
        for k, v in re.findall(r'(MM_SIGN_\w+)\s*=\s*(\d+)', m.group(1)): consts[k] = int(v)
    for m in re.finditer(r'static const (\w+) (\w+)\[4\]\s*=\s*\{(.*?)\};', s, re.S):
        typ, name, body = m.groups()
        tables[name] = [[x.strip() for x in e.split(',')] for e in re.findall(r'\{([^{}]*)\}', body)]
    return arrays, consts, tables

arrays, consts, tables = {}, {}, {}
for fn in ('vehicle_art.h', 'cockpit_art.h', 'store_art.h'):
    a, c, t = parse(fn); arrays.update(a); consts.update(c); tables.update(t)

blob = bytearray(); off = {}
for name, (t, vals) in arrays.items():
    if len(blob) & 1: blob.append(0)                     # uint16 data stays aligned
    off[name] = len(blob)
    blob += struct.pack('<%d%s' % (len(vals), 'H' if t == 'uint16_t' else 'B'), *vals)
z = zlib.compress(bytes(blob), 9)

with open(OUT, 'w') as f:
    f.write('// Generated by tools/sprites/pack_art.py. Do not edit.\n// %d bytes of art, deflated to %d (unpacked into PSRAM at boot by art.cpp)\n' % (len(blob), len(z)))
    f.write('#pragma once\n#include <stdint.h>\nnamespace mantis {\nnamespace artpack {\n')
    f.write('static const uint32_t RAW_SIZE = %d, Z_SIZE = %d;\n' % (len(blob), len(z)))
    f.write('static const uint8_t Z[%d] = {\n' % len(z))
    for i in range(0, len(z), 40): f.write('  ' + ','.join(str(b) for b in z[i:i + 40]) + ',\n')
    f.write('};\n')
    # VehArt {w, h, frames, ax, ay, pal, px}
    f.write('struct VehMeta { uint8_t w, h, frames; int8_t ax, ay; uint32_t pal, px; };\n')
    f.write('static const VehMeta VEH[4] = {%s};\n' % ', '.join('{%s, %s, %s, %s, %s, %d, %d}' % (e[0], e[1], e[2], e[3], e[4], off[e[5]], off[e[6]]) for e in tables['VEH_ART']))
    # CockArt {pal, px, wx, wy, wr}
    f.write('struct CockMeta { uint32_t pal, px; int8_t wx, wy, wr; };\n')
    f.write('static const CockMeta COCK[4] = {%s};\n' % ', '.join('{%d, %d, %s, %s, %s}' % (off[e[0]], off[e[1]], e[2], e[3], e[4]) for e in tables['COCK_ART']))
    # SideArt {w, h, px}
    f.write('struct SideMeta { uint8_t w, h; uint32_t px; };\n')
    for nm in ('SIDE_ART', 'REAR_ART'):
        f.write('static const SideMeta %s[4] = {%s};\n' % (nm.split('_')[0], ', '.join('{%s, %s, %d}' % (e[0], e[1], off[e[2]]) for e in tables[nm])))
    f.write('static const uint32_t MM_SIGN_OFF = %d, MM_SIGN_L_OFF = %d;\n' % (off['MM_SIGN'], off['MM_SIGN_L']))
    f.write('static const uint8_t MM_W = %d, MM_H = %d, MM_AX = %d, MM_AXL = %d;\n' % (consts['MM_SIGN_W'], consts['MM_SIGN_H'], consts['MM_SIGN_AX'], consts['MM_SIGN_AXL']))
    f.write('}\n}\n')
print('art: %d bytes -> %d packed (%.1f KB saved)' % (len(blob), len(z), (len(blob) - len(z)) / 1024))
